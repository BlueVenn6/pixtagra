"""Generate a rights-clear, content-distinct image corpus for UI stress tests."""
import argparse, hashlib, json
from pathlib import Path
from PIL import Image, ImageDraw

def main():
    p=argparse.ArgumentParser();p.add_argument('--output',required=True);p.add_argument('--count',type=int,default=500);a=p.parse_args()
    root=Path(a.output);root.mkdir(parents=True,exist_ok=True);records=[]
    for i in range(a.count):
        size=(640+(i%11)*23,360+(i%7)*19); path=root/f'synthetic-{i:04d}.jpg'
        with Image.new('RGB',size,((i*37)%255,(i*71)%255,(i*113)%255)) as im:
            d=ImageDraw.Draw(im);d.rectangle((i%size[0],0,size[0]-1,size[1]//3),fill=((i*17)%255,80,190));x=i*3%max(1,size[0]//3);y=i*5%max(1,size[1]//3);d.ellipse((x,y,x+size[0]//3,y+size[1]//3),fill=(220,(i*29)%255,60));d.text((20,20),f'PixTagra stress image {i:04d}',fill='white');im.save(path,quality=88)
        raw=path.read_bytes()
        with Image.open(path) as decoded:
            rgb=decoded.convert('RGB'); pixels=hashlib.sha256(str(rgb.size).encode()+rgb.tobytes()).hexdigest()
            records.append({'file':path.name,'source_url':'generated://pix-tagra-stress','license':'generated by PixTagra test harness','sha256':hashlib.sha256(raw).hexdigest(),'pixels_sha256':pixels,'width':decoded.width,'height':decoded.height,'bytes':len(raw)})
    (root/'manifest.json').write_text(json.dumps({'dataset':'PixTagra generated stress corpus','images_uploaded_to_api':False,'unique_decoded_images':len(records),'images':records},indent=2),encoding='utf-8')
    print(json.dumps({'count':len(records),'bytes':sum(x['bytes'] for x in records),'manifest':str(root/'manifest.json')}))
if __name__=='__main__':main()
